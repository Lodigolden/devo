from projects.cpp_sw import Cpp_Sw
from projects.python import Python

import argparse

# --------------------------------------------------------------------------------------------------
def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('-t', '--type', help='Enter Project Type')

    args = parser.parse_args()

    match args.type:
        case 'python':
            Python()
        case 'cpp_sw':
            Cpp_Sw()

# --------------------------------------------------------------------------------------------------
if __name__ == "__main__":
    main()
